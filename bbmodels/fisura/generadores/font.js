function textWidth(font, s, gap = 1) { return [...s].reduce((w, ch) => w + font[ch][0].length + gap, -gap); }
// devuelve lista de [x,y] encendidos relativos
function textPixels(font, s, gap = 1) {
  const out = []; let x = 0;
  for (const ch of s) { const g = font[ch]; g.forEach((row, y) => [...row].forEach((b, i) => { if (b === '1') out.push([x + i, y]); })); x += g[0].length + gap; }
  return out;
}
